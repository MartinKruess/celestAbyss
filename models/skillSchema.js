effectSchema.pre('validate', function () {
    const requireField = field => {
        if (this[field] === undefined || this[field] === null) this.invalidate(field, `${field} is required for ${this.type}`);
    };
    if (!['deathReprieve', 'control'].includes(this.type)) { requireField('value'); requireField('unit'); }
    if (this.type === 'control') requireField('controlKind');
    if (this.type === 'resourceGain') requireField('resource');
    if (this.type === 'experienceBonus') requireField('experienceSource');
    if (this.type === 'deathReprieve') {
        requireField('trigger');
        if (this.diesAtEnd !== true) this.invalidate('diesAtEnd', 'Death reprieve must end in death');
    }
    if (this.type === 'statModifier') requireField('stat');
    if (this.type === 'shield') {
        requireField('reference');
        if (!this.damageTypes.length) this.invalidate('damageTypes', 'Shield damage types are required');
    }
    if (this.type === 'damageBonus') requireField('appliesTo');
    if (['cooldownReduction', 'castTimeReduction'].includes(this.type)) requireField('appliesTo');
    if (this.type === 'resourceCostReduction') { requireField('resource'); requireField('appliesTo'); }
    if (this.type === 'damageReplay') {
        requireField('hitChance'); requireField('damageSource');
        if (this.excludeReplayDamage !== true) this.invalidate('excludeReplayDamage', 'Replay damage must not be collected again');
    }
    if (this.type === 'heal' && this.unit === 'fraction') requireField('reference');
    if (this.type === 'resourceDrain') {
        requireField('resource');
        if (!this.intervalSource) requireField('intervalSeconds');
        if (this.unit === 'fraction') requireField('reference');
    }
    if (this.type !== 'statModifier' && this.value < 0) this.invalidate('value', 'Value must not be negative');
});

