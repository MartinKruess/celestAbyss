skillSchema.pre('validate', function () {
    if (this.classificationVersion === 1 && !this.type) this.invalidate('type', 'Canonical skill type is required');
    if (this.damageType && this.type !== 'skill') this.invalidate('damageType', 'Only direct skills have a damage type');
    if (this.effectKind === 'movement' && (this.type !== 'buff' || this.target !== 'self')) this.invalidate('effectKind', 'Movement is a self-targeted buff');
    if (this.type === 'selfBuff' && this.target !== 'self') this.invalidate('target', 'Self buffs must target self');
});

