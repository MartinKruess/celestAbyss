import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {skillForClass} from '../services/skillLearningLevel.js';
import {curveValue} from '../services/rotationDamage.js';
const read=async p=>JSON.parse(await fs.readFile(p,'utf8'));
const path='data/balancing/class-comparison-level60.json';
const [c,skills]=await Promise.all([read(path),read('data/skills.json')]);
const backup='data/balancing/history/before-knight-block-comparison-'+Date.now();
await fs.mkdir(backup,{recursive:true});
await fs.copyFile(path,backup+'/comparison.json');
await fs.copyFile('docs/balancing/class-comparison.md',backup+'/comparison.md');
const row=c.passiveRows.find(r=>r.key==='knight');assert(row.includedSkills.includes(28));
const permanentBlock=row.includedSkills.reduce((sum,nr)=>{const s=skillForClass(skills.find(s=>s.nr===nr),'knight');return sum+(s.statScaling?.block?curveValue(s.statScaling.block,s.maxSkillLv):s.block??0);},0);
const equipped=c.rows.find(r=>r.key==='knight').equipped.block??0;
row.stats.block=equipped+permanentBlock;
await fs.writeFile(path,JSON.stringify(c,null,2)+'\n');
const mdPath='docs/balancing/class-comparison.md';let md=await fs.readFile(mdPath,'utf8');
const start=md.indexOf('## Vergleich mit permanenten Passiven vor dem Kampf');assert(start>=0);
const end=md.indexOf('\n## ',start+1);const section=md.slice(start,end<0?undefined:end);
const blockIndex=c.fields.findIndex(([key])=>key==='block');assert(blockIndex>=0);
const updated=section.replace(/^\| Ritter \|.*$/m,line=>{const cells=line.split('|');cells[blockIndex+2]=' '+row.stats.block.toLocaleString('de-DE')+' ';return cells.join('|');});
assert.notEqual(section,updated);
md=md.slice(0,start)+updated+(end<0?'':md.slice(end));await fs.writeFile(mdPath,md);
console.log('Knight permanent Block recalculated: '+row.stats.block+'. Other comparison stats preserved.');
