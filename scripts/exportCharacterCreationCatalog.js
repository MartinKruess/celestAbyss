import fs from 'node:fs/promises';
import { classRaces } from '../services/characterPolicy.js';
import { canonicalStatClass } from '../services/characterStats.js';
const templates = JSON.parse(await fs.readFile(new URL('../data/class-templates.json', import.meta.url), 'utf8'));
const roles = { 'damage dealer': 'Schaden', 'starker dd': 'Schaden', Offtank: 'Off-Tank', Fury: 'Furor',
  Elemental: 'Elementarmagie', Supporter: 'Unterstützung', Buffer: 'Unterstützung', Potions: 'Tränke',
  'leichter Tank': 'Leichter Tank', Heiler: 'Heilung', Magier: 'Magie', Kämpfer: 'Kampf', Tank: 'Tank' };
const weapons = { '1 handed axe': 'Einhandaxt', '2 handed ax': 'Zweihandaxt', 'Staff/Wand': 'Stab / Zauberstab' };
const attributes = { 'Physical Attack': 'physischer Angriff', 'Magical Attack': 'magischer Angriff' };
const quote = s => `TEXT(${JSON.stringify(s)})`;
const records = Object.entries(classRaces).map(([key, race]) => {
  const t = templates.find(c => c.key === canonicalStatClass(key));
  const role = t?.roleNotes?.map(v => roles[v] || v).join(' · ') || '';
  return [key, race, t?.displayName_de || t?.displayName || key, role,
    t ? `${t.attributeNotes ? `Schwerpunkt: ${attributes[t.attributeNotes] || t.attributeNotes}.` : 'Wähle diese Klasse für deine neue Spielfigur.'}`
      : 'Für diese Klasse ist die Charaktererstellung noch nicht vorbereitet.',
    t?.weaponNotes ? `Waffen: ${weapons[t.weaponNotes] || t.weaponNotes}` : 'Waffenprofil folgt.', Boolean(t)];
});
const content = '// Generated by scripts/exportCharacterCreationCatalog.js from class-templates.json and characterPolicy.js.\n'
  + '// Presentation metadata only; backend-provided allowed keys still gate creation. No class/race migration.\n'
  + 'static const TArray<FCelestCreationClass> CreationClasses = {\n'
  + records.map(r => '    { ' + r.map(v => typeof v === 'boolean' ? String(v) : quote(v)).join(', ') + ' },').join('\n')
  + '\n};\n';
await fs.writeFile(new URL('../unreal/Plugins/CelestFrontendApi/Source/CelestFrontendApi/Private/CelestCreationCatalog.inl', import.meta.url), content);
console.log(`Exported ${records.length} current API class entries; ${records.filter(r => r[6]).length} confirmed definitions.`);
